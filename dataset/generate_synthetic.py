"""
Synthetic Acoustic Signal Generator for Water Leak Detection
Author: Jayprakash Maurya (T.Y. B.Sc. IT - Vidyalankar School of Information Technology)
Project: Detecting Water Leaks Using Acoustic Signals

This script generates synthetic acoustic signals simulating water flow and leaks
in municipal/industrial water pipelines.

Signal Characteristics:
- Sampling Rate: 8000 Hz
- Duration: 5.0 seconds (40,000 samples)
- Normal: Low-pass filtered flow noise + 50 Hz power hum + low-frequency pump rumble
- Leak: Normal background + band-limited turbulent hiss (500-3000 Hz) + intermittent bursts
- Realism: Realistic amplitude variations, background noise, and borderline/hard cases.
"""

import os
import numpy as np
from scipy import signal
import soundfile as sf
import matplotlib.pyplot as plt

# ==========================================
# CONFIGURATION CONSTANTS
# ==========================================
SAMPLE_RATE = 8000       # 8 kHz sampling rate (sufficient for pipe acoustics up to 4 kHz Nyquist)
DURATION = 5.0           # 5.0 seconds per audio recording
N_SAMPLES = int(SAMPLE_RATE * DURATION)  # 40,000 samples
FILES_PER_CLASS = 60     # 60 normal files + 60 leak files = 120 files total
RANDOM_SEED = 42         # Fixed seed for 100% reproducible viva demonstrations

# Directories
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
NORMAL_DIR = os.path.join(BASE_DIR, "normal")
LEAK_DIR = os.path.join(BASE_DIR, "leak")


def generate_time_array(duration: float, sr: int) -> np.ndarray:
    """Generate the discrete time axis array."""
    return np.linspace(0, duration, int(duration * sr), endpoint=False)


def generate_pink_noise(n_samples: int, rng: np.random.RandomState) -> np.ndarray:
    """
    Generate pink/brownish low-pass noise representing steady fluid flow.
    Generated by integrating white noise and normalizing.
    """
    white = rng.randn(n_samples)
    # 1st-order low-pass IIR filter to give pinkish/brownish slope (-3 to -6 dB/octave)
    b = [0.05]
    a = [1.0, -0.95]
    pink = signal.lfilter(b, a, white)
    # Remove DC component
    pink = pink - np.mean(pink)
    return pink / (np.std(pink) + 1e-9)


def generate_normal_base(
    n_samples: int,
    sr: int,
    rng: np.random.RandomState,
    flow_level: float = 0.5,
    pump_level: float = 0.3,
    hum_level: float = 0.15,
) -> np.ndarray:
    """
    Generate normal pipeline baseline acoustic signal:
    1. Steady water flow friction (pink-filtered noise).
    2. Electrical power-line hum (50 Hz + 100 Hz harmonic).
    3. Low-frequency mechanical pump rumble (20-35 Hz).
    4. Ambient background noise.
    """
    t = generate_time_array(n_samples / sr, sr)

    # 1. Steady flow friction
    flow = generate_pink_noise(n_samples, rng) * flow_level

    # 2. 50 Hz power hum with 100 Hz harmonic
    hum_phase = rng.uniform(0, 2 * np.pi)
    hum = (
        np.sin(2 * np.pi * 50.0 * t + hum_phase)
        + 0.3 * np.sin(2 * np.pi * 100.0 * t + hum_phase)
    ) * hum_level

    # 3. Mechanical pump rumble (random frequency between 20 and 35 Hz)
    pump_freq = rng.uniform(20.0, 35.0)
    pump_phase = rng.uniform(0, 2 * np.pi)
    # Slight slow amplitude modulation representing rotational cycle
    pump_mod = 1.0 + 0.25 * np.sin(2 * np.pi * rng.uniform(1.0, 3.0) * t)
    pump = np.sin(2 * np.pi * pump_freq * t + pump_phase) * pump_mod * pump_level

    # 4. Light background white noise
    bg_noise = rng.randn(n_samples) * rng.uniform(0.02, 0.06)

    combined = flow + hum + pump + bg_noise
    return combined


def generate_leak_component(
    n_samples: int,
    sr: int,
    rng: np.random.RandomState,
    center_freq: float,
    bandwidth: float,
    leak_strength: float = 0.8,
) -> np.ndarray:
    """
    Generate leak acoustic component:
    - High-pressure water escaping through pipe orifice creates turbulent hiss.
    - Centered in 500-3000 Hz band (typically 800-2400 Hz for municipal pipes).
    - Includes pressure bursts and flow turbulence modulation.
    """
    t = generate_time_array(n_samples / sr, sr)

    # Raw wideband turbulence
    raw_hiss = rng.randn(n_samples)

    # Design bandpass filter around the leak's acoustic resonance
    low = max(150.0, center_freq - bandwidth / 2.0)
    high = min(sr / 2.0 - 50.0, center_freq + bandwidth / 2.0)
    sos = signal.butter(4, [low, high], btype="bandpass", fs=sr, output="sos")
    filtered_hiss = signal.sosfiltfilt(sos, raw_hiss)

    # Normalize filtered hiss
    filtered_hiss = filtered_hiss / (np.std(filtered_hiss) + 1e-9)

    # Add acoustic burst modulation (turbulent vortex shedding / fluctuating escape rate)
    burst_freq = rng.uniform(1.5, 6.0)  # 1.5 to 6 bursts per second
    modulation = 1.0 + 0.45 * np.sin(2 * np.pi * burst_freq * t + rng.uniform(0, 2 * np.pi))

    # Occasional transient spikes simulating water pressure bubbles/splashes
    n_spikes = rng.randint(2, 6)
    spike_train = np.zeros(n_samples)
    for _ in range(n_spikes):
        idx = rng.randint(0, n_samples - 200)
        spike_train[idx : idx + 100] += rng.uniform(0.3, 0.7) * np.hanning(100)

    leak_signal = (filtered_hiss * modulation + spike_train) * leak_strength
    return leak_signal


def generate_sample(
    is_leak: bool,
    rng: np.random.RandomState,
    is_hard_case: bool = False,
) -> np.ndarray:
    """
    Generate a full 5-second acoustic recording.

    Parameters:
    - is_leak: True for leak class, False for normal class.
    - rng: Numpy RandomState for deterministic reproducibility.
    - is_hard_case: If True, generate borderline sample (weak leak or loud normal)
                    to ensure model doesn't overfit and mirrors realistic overlap.
    """
    # Base amplitude scaling (pipe acoustic attenuation variation across installations)
    overall_gain = rng.uniform(0.35, 0.95)

    if not is_leak:
        # NORMAL PIPELINE SOUND
        if is_hard_case:
            # LOUDER / TURBULENT normal flow (e.g. valve throttling or high water demand)
            flow_level = rng.uniform(0.70, 0.95)
            pump_level = rng.uniform(0.40, 0.65)
            hum_level = rng.uniform(0.18, 0.35)
            # Add moderate valve turbulence in 500-900 Hz band to create realistic boundary overlap
            t = generate_time_array(N_SAMPLES / SAMPLE_RATE, SAMPLE_RATE)
            valve_noise = rng.randn(N_SAMPLES)
            sos_valve = signal.butter(3, [500, 950], btype="bandpass", fs=SAMPLE_RATE, output="sos")
            valve_filtered = signal.sosfiltfilt(sos_valve, valve_noise)
            valve_component = (valve_filtered / (np.std(valve_filtered) + 1e-9)) * rng.uniform(0.25, 0.40)
        else:
            flow_level = rng.uniform(0.30, 0.60)
            pump_level = rng.uniform(0.18, 0.40)
            hum_level = rng.uniform(0.08, 0.20)
            valve_component = np.zeros(N_SAMPLES)

        base_sig = generate_normal_base(
            N_SAMPLES,
            SAMPLE_RATE,
            rng,
            flow_level=flow_level,
            pump_level=pump_level,
            hum_level=hum_level,
        )
        sig = base_sig + valve_component
    else:
        # LEAK PIPELINE SOUND
        base_sig = generate_normal_base(
            N_SAMPLES,
            SAMPLE_RATE,
            rng,
            flow_level=rng.uniform(0.35, 0.65),
            pump_level=rng.uniform(0.18, 0.38),
            hum_level=rng.uniform(0.08, 0.20),
        )

        center_freq = rng.uniform(850.0, 2300.0)
        bandwidth = rng.uniform(400.0, 1000.0)

        if is_hard_case:
            # WEAK / MICRO LEAK (pinhole leak with faint hiss, easily masked by flow)
            leak_strength = rng.uniform(0.12, 0.24)
        else:
            # PROMINENT LEAK
            leak_strength = rng.uniform(0.55, 1.05)

        leak_sig = generate_leak_component(
            N_SAMPLES,
            SAMPLE_RATE,
            rng,
            center_freq=center_freq,
            bandwidth=bandwidth,
            leak_strength=leak_strength,
        )

        sig = base_sig + leak_sig

    # Apply overall gain and prevent hard clipping
    sig = sig * overall_gain
    peak = np.max(np.abs(sig))
    if peak > 0.95:
        sig = sig * (0.95 / peak)

    return sig.astype(np.float32)


def save_example_plots(normal_sig: np.ndarray, leak_sig: np.ndarray, sr: int):
    """
    Generate and save professional Waveform and Spectrogram comparison plots
    for inclusion in college project documentation and report.
    """
    for sig_data, label, filename in [
        (normal_sig, "NORMAL PIPELINE CONDITION", "normal_example.png"),
        (leak_sig, "POSSIBLE WATER LEAK CONDITION", "leak_example.png"),
    ]:
        fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 6), tight_layout=True)

        # 1. Waveform Plot
        t = np.linspace(0, len(sig_data) / sr, len(sig_data))
        ax1.plot(t, sig_data, color="#1f77b4" if "NORMAL" in label else "#d62728", lw=0.8)
        ax1.set_title(f"Acoustic Waveform - {label}", fontsize=12, fontweight="bold")
        ax1.set_xlabel("Time (seconds)")
        ax1.set_ylabel("Amplitude")
        ax1.set_ylim(-1.05, 1.05)
        ax1.grid(True, linestyle="--", alpha=0.6)

        # 2. Spectrogram Plot
        f, t_spec, Sxx = signal.spectrogram(sig_data, fs=sr, nperseg=512, noverlap=256)
        Sxx_db = 10 * np.log10(Sxx + 1e-10)
        im = ax2.pcolormesh(t_spec, f, Sxx_db, shading="gouraud", cmap="magma")
        ax2.set_title(f"Acoustic Spectrogram (FFT) - {label}", fontsize=12, fontweight="bold")
        ax2.set_xlabel("Time (seconds)")
        ax2.set_ylabel("Frequency (Hz)")
        ax2.set_ylim(0, 4000)
        cbar = fig.colorbar(im, ax=ax2, orientation="vertical", pad=0.02)
        cbar.set_label("Power Spectral Density (dB)")

        save_path = os.path.join(BASE_DIR, filename)
        plt.savefig(save_path, dpi=200)
        plt.close(fig)
        print(f"Saved example plot: {save_path}")


def main():
    """Generate all synthetic files for both classes."""
    print("=" * 60)
    print("STEP 1: GENERATING SYNTHETIC ACOUSTIC WATER LEAK DATASET")
    print("=" * 60)
    print(f"Sampling Rate: {SAMPLE_RATE} Hz")
    print(f"Duration:      {DURATION} seconds per file ({N_SAMPLES} samples)")
    print(f"Files:         {FILES_PER_CLASS} Normal, {FILES_PER_CLASS} Leak (Total {FILES_PER_CLASS * 2})")
    print(f"Random Seed:   {RANDOM_SEED} (fully deterministic)")

    os.makedirs(NORMAL_DIR, exist_ok=True)
    os.makedirs(LEAK_DIR, exist_ok=True)

    rng = np.random.RandomState(RANDOM_SEED)

    # Designate borderline/hard cases distributed across the dataset (e.g. indices 7, 17, 27, 37, 47, 57)
    # This guarantees hard cases are represented in Train, Validation, and Test splits.
    hard_indices = set(range(7, FILES_PER_CLASS, 10))

    sample_normal_sig = None
    sample_leak_sig = None

    # Generate NORMAL samples
    print("\nGenerating Normal Pipeline Acoustic Signals...")
    for i in range(FILES_PER_CLASS):
        is_hard = i in hard_indices
        sig = generate_sample(is_leak=False, rng=rng, is_hard_case=is_hard)
        filepath = os.path.join(NORMAL_DIR, f"normal_{i+1:03d}.wav")
        sf.write(filepath, sig, SAMPLE_RATE, subtype="PCM_16")
        if i == 0:
            sample_normal_sig = sig

    print(f"Successfully generated {FILES_PER_CLASS} normal files in: {NORMAL_DIR}")

    # Generate LEAK samples
    print("\nGenerating Possible Leak Acoustic Signals...")
    for i in range(FILES_PER_CLASS):
        is_hard = i in hard_indices
        sig = generate_sample(is_leak=True, rng=rng, is_hard_case=is_hard)
        filepath = os.path.join(LEAK_DIR, f"leak_{i+1:03d}.wav")
        sf.write(filepath, sig, SAMPLE_RATE, subtype="PCM_16")
        if i == 0:
            sample_leak_sig = sig

    print(f"Successfully generated {FILES_PER_CLASS} leak files in:   {LEAK_DIR}")

    # Save waveform and spectrogram example images
    print("\nGenerating example waveform and spectrogram figures...")
    save_example_plots(sample_normal_sig, sample_leak_sig, SAMPLE_RATE)

    # Print summary
    print("\n" + "=" * 60)
    print("DATASET GENERATION SUMMARY")
    print("=" * 60)
    print(f"Total Normal Files: {len(os.listdir(NORMAL_DIR))}")
    print(f"Total Leak Files:   {len(os.listdir(LEAK_DIR))}")
    file_size_kb = os.path.getsize(os.path.join(NORMAL_DIR, "normal_001.wav")) / 1024
    print(f"Audio File Size:    ~{file_size_kb:.1f} KB per file (16-bit PCM WAV)")
    print("Done! Ready for Preprocessing and Feature Extraction.")
    print("=" * 60)


if __name__ == "__main__":
    main()
